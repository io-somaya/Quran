  /**
   * استرجاع جميع الفئات المتاحة
   */
  function getAllCategories() {
    return CATEGORIES;
  }

  /**
   * استرجاع قائمة الأذكار بحسب الفئة
   * @param {string} categoryId morning | evening | after_prayer | sleep | quranic_duas | tasbeeh
   */
  function getAdhkarByCategory(categoryId) {
    return ADHKAR_DATABASE[categoryId] || [];
  }

  /**
   * استرجاع ذكر محدد بواسطة المعرف ID
   * @param {string} dhikrId 
   */
  function getDhikrById(dhikrId) {
    for (const key of Object.keys(ADHKAR_DATABASE)) {
      const found = ADHKAR_DATABASE[key].find(item => item.id === dhikrId);
      if (found) return { ...found, category: key };
    }
    return null;
  }

  /**
   * استرجاع عناصر السبحة الإلكترونية
   */
  function getTasbeehItems() {
    return ADHKAR_DATABASE.tasbeeh;
  }

  /**
   * استرجاع دعاء قرآني عشوائي
   */
  function getRandomQuranicDua() {
    const list = ADHKAR_DATABASE.quranic_duas;
    const index = Math.floor(Math.random() * list.length);
    return list[index];
  }

  /**
   * استرجاع ذكر عشوائي ملهم للبطاقة اليومية أو التنبيهات
   */
  function getRandomDhikr() {
    const categories = ['morning', 'evening', 'quranic_duas', 'tasbeeh'];
    const cat = categories[Math.floor(Math.random() * categories.length)];
    const list = ADHKAR_DATABASE[cat];
    return list[Math.floor(Math.random() * list.length)];
  }

